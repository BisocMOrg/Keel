def python_outputs(model):
    outputs = {}
    table = model.spec.packages
    for package in sorted(set(table.values())):
        directory = os.path.join(PY_SOURCE, *package.split(".")) if package else PY_SOURCE
        if not os.path.isfile(os.path.join(directory, "__init__.py")):
            fail("the package table names %s, which has no %s/__init__.py"
                 % (py_package(package), os.path.relpath(directory, REPOSITORY).replace(os.sep, "/")))
        outputs[os.path.join(directory, "_generated.py")] = python_package(model, package)
    if model.spec.name == "keel":
        internal, constants, groups = os.path.join(PY_SOURCE, "_internal"), PY_SOURCE, ("keel_abi", "keel_limit")
    else:
        internal = os.path.join(PY_SOURCE, "_internal", "camera")
        constants, groups = os.path.join(PY_SOURCE, "camera"), ("keel_camera_abi", "keel_camera_limit")
        if not os.path.isfile(os.path.join(internal, "__init__.py")):
            fail("keel/_internal/camera/__init__.py is missing")
    outputs[os.path.join(internal, "_generated.py")] = python_internal(model)
    outputs[os.path.join(constants, "abi.py")] = python_constants(model, groups[0], *PY_CONSTANT_DOCS[groups[0]])
    outputs[os.path.join(constants, "limits.py")] = python_constants(model, groups[1], *PY_CONSTANT_DOCS[groups[1]])
    return outputs



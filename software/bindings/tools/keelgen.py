def py_header(summary, body, notice=NOTICE):
    """The licence lines, the generator notice and the module docstring."""
    return ["# SPDX-License-Identifier: MIT", "# Copyright (c) 2026 BisocM", "# " + notice] + \
        py_doc(body, "", summary=summary) + [""]


def py_doc(text, indent, summary=None, fallback=None):
    """A docstring block: a one-line summary, then the text wrapped to the line limit.

    Without an explicit summary, the first sentence of text is the summary; when it does not fit on one line,
    fallback is the summary and the whole text follows it.
    """
    width = LINE_LIMIT - len(indent)
    paragraphs = []
    body = text
    if summary is None:
        summary, body = first_sentence(text.split("\n\n")[0])
        rest = text.split("\n\n")[1:]
        body = "\n\n".join(([body] if body else []) + rest)
        if len(indent) + 6 + len(summary) > LINE_LIMIT and fallback:
            summary, body = fallback, text
    if len(indent) + 6 + len(summary) > LINE_LIMIT:
        fail("the summary %r is too long for one docstring line" % summary)
    for paragraph in body.split("\n\n"):
        if paragraph:
            paragraphs.append(textwrap.wrap(paragraph, width, break_on_hyphens=False, break_long_words=False))
    if not paragraphs:
        return [indent + '"""' + summary + '"""']
    lines = [indent + '"""' + summary, ""]
    for number, paragraph in enumerate(paragraphs):
        if number:
            lines.append("")
        lines.extend(indent + line for line in paragraph)
    lines.append(indent + '"""')
    return lines


def py_attr_doc(text, indent):
    """An attribute docstring (free-form text after an assignment)."""
    text = text or "See keel.h."
    width = LINE_LIMIT - len(indent) - 6
    wrapped = []
    for number, paragraph in enumerate(text.split("\n\n")):
        if number:
            wrapped.append("")
        wrapped.extend(textwrap.wrap(paragraph, width, break_on_hyphens=False, break_long_words=False))
    if len(wrapped) == 1:
        return [indent + '"""' + wrapped[0] + '"""']
    return [indent + '"""' + wrapped[0]] + [indent + line if line else "" for line in wrapped[1:]] + \
        [indent + '"""']


def py_signature(name, params, result):
    """A def line formatted the way ruff format formats it."""
    one = "def %s(%s) -> %s:" % (name, ", ".join(params), result)
    if len(one) <= LINE_LIMIT:
        return [one]
    hugged = "    " + ", ".join(params)
    if len(hugged) <= LINE_LIMIT:
        return ["def %s(" % name, hugged, ") -> %s:" % result]
    return ["def %s(" % name] + ["    %s," % param for param in params] + [") -> %s:" % result]


def py_imports(standard, keel_names):
    """The import block the way ruff sorts and formats it.

    standard is the list of standard-library import lines, already in order; keel_names maps a keel module to the
    names imported from it. A from-import longer than the line limit takes one name per line.
    """
    lines = ["from __future__ import annotations"]
    if standard:
        lines += [""] + standard
    if keel_names:
        lines.append("")
    for module in sorted(keel_names):
        names = sorted(set(keel_names[module]))
        one = "from %s import %s" % (module, ", ".join(names))
        if len(one) <= LINE_LIMIT:
            lines.append(one)
        else:
            lines += ["from %s import (" % module] + ["    %s," % name for name in names] + [")"]
    return lines


def py_package(package):
    """The dotted name of a package of the PACKAGES table: keel for the root, keel.<package> otherwise."""
    return "keel.%s" % package if package else "keel"


def py_module(type_name):
    """The generated module that declares a public type of either header."""
    return py_package(ALL_PACKAGES[type_name]) + "._generated"


def py_struct_name(struct):
    return struct.type_name + "Struct"


def py_field_type(model, item):
    if model.enum_of(item.binding):
        return model.enum_of(item.binding).type_name
    return "str" if item.binding in (PATH, TEXT) else "int"


def py_struct_types(model, struct):
    """The types a data class refers to: the enums of its fields and those its properties name."""
    names = {model.enum_of(item.binding).type_name for item in struct.fields if model.enum_of(item.binding)}
    for _, _, expression, _ in model.spec.properties.get(struct.type_name, []):
        names.update(word for word in re.findall(r"\b[A-Z]\w*", expression) if word in ALL_PACKAGES)
    return names


def py_enums(enums):
    lines = []
    for enum in enums:
        doc = clean(enum.doc)
        doc += "\n\nC enum: %s. Members are the enumerators without the prefix %s." % (enum.name, enum.prefix)
        if enum.kind == "value":
            lines += ["", "", "class %s(ValueEnum):" % enum.type_name]
            doc += (" A value this binding does not know becomes the pseudo-member %s_<value>, so a newer "
                    "library's code is kept, never refused." % SENTINEL)
        else:
            lines += ["", "", "class %s(enum.IntFlag, boundary=enum.KEEP):" % enum.type_name]
            doc += " Bits this binding does not know are kept."
        lines += py_doc(doc, "    ", fallback="The values of the C enum %s." % enum.name)
        for enumerator in enum.enumerators:
            lines += ["", "    %s = %d" % (enumerator.member, enumerator.value)]
            lines += py_attr_doc(clean(enumerator.doc), "    ")
    return lines


def py_dataclass(model, struct):
    name = struct.type_name
    lines = ["", "", "@dataclass(frozen=True, slots=True)", "class %s:" % name]
    doc = clean(struct.doc) + "\n\nC struct: %s. Fields keep the C names and order." % struct.name
    lines += py_doc(doc, "    ", fallback="The contents of the C struct %s." % struct.name)
    for item in struct.fields:
        if item.binding in (SIZE, RESERVED):
            continue
        lines += ["", "    %s: %s" % (item.name, py_field_type(model, item))]
        lines += py_attr_doc(clean(item.doc), "    ")
    for prop, kind, expression, text in model.spec.properties.get(name, []):
        lines += ["", "    @property", "    def %s(self) -> %s:" % (prop, kind), '        """%s"""' % text,
                  "        return %s" % expression]
    return lines


def py_converter(model, struct):
    name = struct.type_name
    article = "an" if name[0] in "AEIOU" else "a"
    lines = ["", "", "def convert_%s(raw: %s) -> %s:" % (snake(name), py_struct_name(struct), name)]
    lines.append('    """Convert a filled %s into %s %s."""' % (py_struct_name(struct), article, name))
    lines.append("    return %s(" % name)
    for item in struct.fields:
        if item.binding in (SIZE, RESERVED):
            continue
        if model.enum_of(item.binding):
            value = "%s(raw.%s)" % (model.enum_of(item.binding).type_name, item.name)
        elif item.binding == PATH:
            value = "os.fsdecode(raw.%s)" % item.name
        elif item.binding == TEXT:
            value = 'raw.%s.decode("utf-8", "replace")' % item.name
        else:
            value = "raw.%s" % item.name
        lines.append("        %s=%s," % (item.name, value))
    lines.append("    )")
    return lines


def py_structs(model):
    lines = []
    for struct in model.structs.values():
        name = py_struct_name(struct)
        lines += ["", "", "class %s(_Struct):" % name]
        lines += py_doc("The ctypes layout of %s (%d bytes)." % (struct.name, struct.size), "    ")
        lines.append("")
        shadowed = any(item.name == "bytes" for item in struct.fields)
        for item in struct.fields:
            annotation = ("builtins.bytes" if shadowed else "bytes") if item.ctype == "char" else "int"
            lines.append("    %s: %s" % (item.name, annotation))
        lines += ["", "    _fields_ = ("]
        for item in struct.fields:
            ctype = "ctypes.c_char * %d" % item.length if item.ctype == "char" else PY_CTYPES[item.ctype]
            lines.append('        ("%s", %s),' % (item.name, ctype))
        lines.append("    )")
    lines += ["", "", "STRUCTS: Final[dict[str, type[_Struct]]] = {"]
    for struct in model.structs.values():
        lines.append('    "%s": %s,' % (struct.name, py_struct_name(struct)))
    lines.append("}")
    lines.append('"""Every ctypes struct by its C name."""')
    return lines


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def py_checked(function, item_name, ctype, value, saturated=SATURATED):
    kind = "saturate_i32" if (function, item_name) in saturated else PY_CHECKS[ctype]
    return '%s("%s", "%s", %s)' % (kind, function, item_name, value)


def py_builders(model):
    lines = []
    for struct in model.structs.values():
        if struct.direction != "in":
            continue
        name = py_struct_name(struct)
        params = ["target: %s" % name, "*"]
        for item in struct.fields:
            if item.binding == SIZE:
                continue
            params.append("%s: %s" % (py_param_name(item.name), "str | bytes" if item.ctype == "char"
                                      else "SupportsIndex"))
        lines += ["", ""] + py_signature("fill_%s" % snake(struct.type_name), params, name)
        saturated = [item.name for item in struct.fields if (struct.name, item.name) in model.spec.saturated]
        texts = [item.name for item in struct.fields if item.ctype == "char"]
        body = "Raises TypeError for a value that is not an integer"
        body += " (or, for a path, not str or bytes)" if texts else ""
        body += " and OverflowError for an integer outside its C type"
        body += "; %s are saturated to the int32_t range instead" % " and ".join(saturated) if saturated else ""
        body += "; ValueError for a path that does not fit" if texts else ""
        body += ". Nothing is written then."
        lines += py_doc(body, "    ", summary="Check every value, then write them all into target (a %s) and return it." % struct.name)
        assignments = []
        for item in struct.fields:
            if item.binding == SIZE:
                continue
            if item.ctype == "char":
                value = 'encode_path("%s", "%s", %s, %d)' % (struct.name, item.name, py_param_name(item.name),
                                                               item.length)
            else:
                value = py_checked(struct.name, item.name, item.ctype, py_param_name(item.name), model.spec.saturated)
            assignments.append((item.name, value))
        for item_name, value in assignments:
            lines.append("    %s = %s" % ("checked_" + item_name, value))
        lines.append("    target.struct_size = ctypes.sizeof(target)")
        for item_name, _ in assignments:
            lines.append("    target.%s = checked_%s" % (item_name, item_name))
        lines.append("    return target")
    return lines


# The opaque handle types: tokens the library issues, passed as c_void_p and never dereferenced.
HANDLES = ("keel_device", "keel_camera", "keel_camera_list")


def py_ctype(model, param):
    if param.base in HANDLES:
        return "_handle" if param.pointers == 1 else "_P(_handle)"
    if param.base == "char" and param.pointers == 1:
        return "_string"
    if param.base == "uint8_t" and param.pointers == 1:
        return "_buffer"
    if param.base == "void" and not param.pointers:
        return "None"
    if param.base in SCALARS:
        return PY_CTYPES[param.base] if not param.pointers else "_P(%s)" % PY_CTYPES[param.base]
    if param.base in model.structs and param.pointers == 1:
        return "_P(%s)" % py_struct_name(model.structs[param.base])
    fail("no ctypes mapping for %s with %d pointers" % (param.base, param.pointers))


def py_prototypes(model):
    lines = ["", "", "PROTOTYPES: Final[dict[str, tuple[Any, list[Any]]]] = {"]
    for function in model.functions.values():
        arguments = ", ".join(py_ctype(model, param) for param in function.params)
        lines.append('    "%s": (%s, [%s]),' % (function.name, py_ctype(model, function.result), arguments))
    lines.append("}")
    lines.append('"""restype and argtypes of all %d functions, in header order."""' % len(model.functions))
    if not model.spec.saturated:
        return lines
    lines += ["", "SATURATED: Final = frozenset("]
    lines.append("    {")
    for function_name, parameter in sorted(model.spec.saturated):
        lines.append('        ("%s", "%s"),' % (function_name, parameter))
    lines += ["    }", ")"]
    lines.append('"""The int32_t positions (function or struct, name) that are saturated instead of range-checked."""')
    return lines


def py_param_name(name):
    """A C name as a Python parameter: a trailing _ for a keyword or a builtin (in_, format_, list_)."""
    return name + "_" if keyword.iskeyword(name) or hasattr(builtins, name) else name


def py_wrappers(model):
    lines = []
    for function in model.functions.values():
        params = ["natives: Natives"]
        call = []
        checks = []
        for param in function.params:
            name = py_param_name(param.name)
            if param.base in HANDLES and param.pointers == 1:
                params.append("%s: int | None" % name)
                call.append(name)
            elif param.base in SCALARS and not param.pointers:
                params.append("%s: SupportsIndex" % name)
                checks.append("    checked_%s = %s" % (param.name, py_checked(function.name, param.name, param.base,
                                                                              name, model.spec.saturated)))
                call.append("checked_" + param.name)
            else:
                params.append("%s: Any" % name)
                call.append(name)
        result = function.result
        if result.base == "char" and result.pointers == 1:
            returns, wrap = "int | None", None
        else:
            returns, wrap = "int", "int(%s)"
        lines += ["", ""] + py_signature(function.name, params, returns)
        if checks:
            summary = "Call %s after checking its integer arguments." % function.name
        else:
            summary = "Call %s." % function.name
        lines += py_doc(function.brief, "    ", summary=summary)
        lines += checks
        expression = 'natives["%s"](%s)' % (function.name, ", ".join(call))
        if wrap is None:
            lines += ["    address: int | None = " + expression, "    return address"]
        else:
            lines += py_return(wrap, function.name, call)
    return lines


def py_return(wrap, function, arguments):
    """The return statement of a call wrapper, split the way ruff format splits a line that is too long."""
    call = 'natives["%s"](%s)' % (function, ", ".join(arguments))
    line = "    return " + wrap % call
    if len(line) <= LINE_LIMIT:
        return [line]
    opening, closing = wrap.split("%s")
    if len("        " + call) <= LINE_LIMIT:
        return ["    return " + opening, "        " + call, "    " + closing]
    head = '        natives["%s"](' % function
    hugged = "            " + ", ".join(arguments)
    if len(hugged) <= LINE_LIMIT:
        return ["    return " + opening, head, hugged, "        )", "    " + closing]
    return ["    return " + opening, head] + ["            %s," % argument for argument in arguments] + \
        ["        )", "    " + closing]



"""Generate the header-derived code of the Keel bindings and check it for drift.

keelgen reads the two public headers of software/libkeel the way SPEC 21 and
26.2 ask binding generators to read them: include/keel/keel.h (libkeel) and
include/keel/camera.h (libkeel-camera, which includes keel.h for the status
codes). For each header:

- the header is preprocessed with `cc -E -P -DKEEL_API=` and libkeel's stand-in
  <stdint.h> (tests/abi/check_constants.py: preprocess, FAKE_STDINT);
- every enumerator is evaluated with check_constants.parse_enums;
- structs and function declarations are parsed with pycparser;
- the doc comment of every declaration is read with the Header reader of
  tests/docs/check_header_docs.py;
- the version macros (KEEL_VERSION_*, KEEL_CAMERA_VERSION_*) give the version
  the generated code restates.

camera.h declares only keel_camera_* names; the keel.h declarations its
preprocessed text also contains are read for reference (a camera struct field
of type keel_status), never generated twice.

Names and binding types come from the explicit tables below, never from
heuristics. keelgen fails when a header and its tables disagree, when an
invariant of the ABI does not hold, or when a binding's version differs from
the header's.

Usage:
  keelgen.py [--lang python|java] [--cc CC]            write the generated files
  keelgen.py --check [--lang python|java] [--cc CC]    regenerate in memory, print
                                                       a diff and fail on any difference
"""


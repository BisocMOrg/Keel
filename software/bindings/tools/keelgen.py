# ------------------------------------------------------------------ docs ----
def clean(text):
    """Doxygen markup to plain text: one string, paragraphs separated by blank lines."""
    text = re.sub(r"<tt>(.*?)</tt>", r"\1", text, flags=re.S)
    text = re.sub(r"@[cpe]\s+([\w.\->:()]+)", r"\1", text)
    text = re.sub(r"(?<![\w:])::(\w)", r"\1", text)
    text = text.replace("\\#", "#").replace("@brief", "").replace("\\", "\\\\")
    paragraphs = [" ".join(part.split()) for part in re.split(r"\n\s*\n", text)]
    return "\n\n".join(part for part in paragraphs if part)


def block_text(block):
    """The body of a /** ... */ block without the comment markers."""
    body = block.strip()
    body = re.sub(r"^/\*\*<?", "", body)
    body = re.sub(r"\*/$", "", body)
    lines = [re.sub(r"^\s*\*(?!/) ?", "", line) for line in body.split("\n")]
    return "\n".join(lines)


def trailing_doc(lines):
    match = re.search(r"/\*\*<(.*?)\*/", " ".join(lines), re.S)
    return match.group(1) if match else None


def read_docs(path):
    """{(kind, name): text} for every enum, enumerator, struct, field and function of the header."""
    header = check_header_docs.Header(path)
    docs = {}
    scope, scope_name, index = None, None, 0
    while index < len(header.lines):
        line = header.lines[index]
        stripped = line.strip()
        enum_match = re.match(r"^enum (keel_\w+) \{", line)
        struct_match = re.match(r"^typedef struct (keel_\w+) \{", line)
        if enum_match:
            scope, scope_name = "enum", enum_match.group(1)
            docs[("enum", scope_name)] = block_text(header.doc_above(index) or "")
        elif struct_match:
            scope, scope_name = "struct", struct_match.group(1)
            docs[("struct", scope_name)] = block_text(header.doc_above(index) or "")
        elif scope and line.startswith("}"):
            scope = None
        elif scope == "enum" and stripped.startswith("KEEL_"):
            name = re.match(r"(KEEL_\w+)", stripped).group(1)
            doc = header.doc_above(index)
            docs[("enumerator", name)] = block_text(doc) if doc else (trailing_doc([line]) or "")
        elif scope == "struct" and stripped and not stripped.startswith(("/*", "*")):
            first = index
            while not header.lines[index].rstrip().endswith(";") and \
                    not re.search(r";\s*/\*\*<.*\*/$", header.lines[index]):
                index += 1
            declaration = " ".join(header.lines[first:index + 1])
            name = re.search(r"(\w+)\s*(\[\d+\])?\s*;", declaration).group(1)
            doc = header.doc_above(first)
            text = block_text(doc) if doc else trailing_doc(header.lines[first:index + 1])
            docs[("field", scope_name, name)] = text or ""
        elif scope is None and check_header_docs.FUNCTION.match(line):
            name = check_header_docs.FUNCTION.match(line).group(3)
            docs[("function", name)] = block_text(header.doc_above(index) or "")
        index += 1
    return docs


def brief(text):
    """The @brief paragraph of a function's block."""
    match = re.search(r"@brief(.*?)(\n\s*\n|\n\s*@|$)", text, re.S)
    return clean(match.group(1)) if match else ""


def first_sentence(text):
    """Split plain text into its first sentence and the rest."""
    match = re.search(r"(?<=[.!?])\s+(?=[A-Z\"(])", text)
    if not match:
        return text, ""
    return text[:match.start()], text[match.end():]


# ----------------------------------------------------------------- parse ----
def preprocess(cc, path=HEADER):
    with tempfile.TemporaryDirectory() as fake:
        with open(os.path.join(fake, "stdint.h"), "w", encoding="utf-8") as handle:
            handle.write(check_constants.FAKE_STDINT)
        with open(os.path.join(fake, "stddef.h"), "w", encoding="utf-8") as handle:
            handle.write(check_constants.FAKE_STDDEF)
        return check_constants.preprocess(cc, path, fake)


def read_version(spec=KEEL_SPEC):
    with open(spec.path, encoding="utf-8") as handle:
        text = handle.read()
    parts = []
    for part in ("MAJOR", "MINOR", "PATCH"):
        match = re.search(r"^#define %s_%s (\d+)$" % (spec.version_macro, part), text, re.M)
        if not match:
            fail("%s does not define %s_%s" % (os.path.basename(spec.path), spec.version_macro, part))
        parts.append(int(match.group(1)))
    return tuple(parts)


def read_list(path):
    with open(path, encoding="utf-8") as handle:
        return [line.strip() for line in handle if line.strip() and not line.startswith("#")]


def layout_pins(path=LAYOUT):
    """{struct: ([(field, offset)], size)} from the FIRST/NEXT/LAST lines of layout.c or camera_layout.c."""
    pins = {}
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            first = re.match(r"FIRST\((keel_\w+), (\w+)\)", line)
            following = re.match(r"NEXT\((keel_\w+), \w+, (\w+), (\d+)\)", line)
            last = re.match(r"LAST\((keel_\w+), \w+, (\d+)\)", line)
            if first:
                pins[first.group(1)] = ([(first.group(2), 0)], None)
            elif following:
                pins[following.group(1)][0].append((following.group(2), int(following.group(3))))
            elif last:
                pins[last.group(1)] = (pins[last.group(1)][0], int(last.group(2)))
    return pins


def type_of(node):
    """(base type name, pointer depth, const) of a pycparser declarator."""
    pointers, const = 0, False
    while type(node).__name__ == "PtrDecl":
        pointers += 1
        node = node.type
    if type(node).__name__ != "TypeDecl":
        fail("unsupported declarator %s" % type(node).__name__)
    const = "const" in node.quals
    inner = node.type
    if type(inner).__name__ == "IdentifierType":
        return " ".join(inner.names), pointers, const
    if type(inner).__name__ == "Struct":
        return inner.name, pointers, const
    fail("unsupported type %s" % type(inner).__name__)


def parse(cc, spec=KEEL_SPEC):
    try:
        import pycparser
    except ImportError:
        fail("pycparser is not installed (pip install pycparser, or apt-get install python3-pycparser)")
    header = os.path.basename(spec.path)
    text = preprocess(cc, spec.path)
    docs = read_docs(spec.path)
    tree = pycparser.CParser().parse(text, header)

    enums, foreign = {}, {}
    known = {}
    for name, body in re.findall(r"\benum\s+(\w+)\s*\{(.*?)\}\s*;", text, re.S):
        if spec.owns(name):
            table, target, enum_docs = spec.enums, enums, docs
        else:
            # A keel.h enum in camera.h's preprocessed text: read with the keel.h table, kept for reference.
            table, target, enum_docs = ENUMS, foreign, {}
        if name not in table:
            fail("enum %s is not in the %s table" % (name, "ENUMS" if table is ENUMS else "CAMERA_ENUMS"))
        type_name, kind, prefix = table[name]
        enum = Enum(name, type_name, kind, prefix, enum_docs.get(("enum", name), ""))
        for enumerator, value in check_constants.parse_enums("enum %s {%s};" % (name, body), known):
            if not enumerator.startswith(prefix):
                fail("%s does not start with the prefix %s of %s" % (enumerator, prefix, name))
            member = enumerator[len(prefix):]
            if not member.isidentifier() or keyword.iskeyword(member) or member[0].isdigit():
                fail("%s gives the member name %r, which is not an identifier" % (enumerator, member))
            if member == SENTINEL or member.startswith(SENTINEL + "_"):
                fail("%s would collide with the open-enum sentinel %s" % (enumerator, SENTINEL))
            enum.enumerators.append(Enumerator(enumerator, member, value,
                                               enum_docs.get(("enumerator", enumerator), "")))
        target[name] = enum
    missing = sorted(set(spec.enums) - set(enums))
    if missing:
        fail("the enum table of %s names enums the header lacks: %s" % (header, " ".join(missing)))
    count = sum(len(enum.enumerators) for enum in enums.values())
    if (len(enums), count) != (spec.enum_count, spec.enumerator_count):
        fail("%s has %d enumerators in %d enums; expected %d in %d (update the invariant deliberately)"
             % (header, count, len(enums), spec.enumerator_count, spec.enum_count))

    structs, functions = {}, {}
    for node in tree.ext:
        kind = type(node).__name__
        if not spec.owns(node.name or ""):
            continue
        if kind == "Typedef" and type(node.type.type).__name__ == "Struct" and node.type.type.decls:
            structs[node.name] = parse_struct(node, {**foreign, **enums}, docs, spec)
        elif kind == "Decl" and type(node.type).__name__ == "FuncDecl":
            functions[node.name] = parse_function(node, docs, spec)
    for name in spec.structs:
        if name not in structs:
            fail("the struct table of %s names struct %s, which the header lacks" % (header, name))
    symbols = read_list(spec.symbols)
    if list(functions) != symbols:
        fail("the functions of %s differ from %s" % (header, os.path.basename(spec.symbols)))
    if list(functions) != list(spec.functions):
        fail("the function table differs from the functions of %s:\n  header: %s\n  table:  %s"
             % (header, " ".join(functions), " ".join(spec.functions)))
    for function_name, parameter in spec.saturated:
        target = structs.get(function_name) or functions.get(function_name)
        names = {item.name: item for item in (target.fields if isinstance(target, Struct) else target.params)} \
            if target else {}
        item = names.get(parameter)
        if item is None or getattr(item, "ctype", getattr(item, "base", None)) != "int32_t":
            fail("SATURATED names %s.%s, which is not an int32_t of the header" % (function_name, parameter))
    return Model(read_version(spec), enums, structs, functions, spec, foreign)


def parse_struct(node, enums, docs, spec=KEEL_SPEC):
    name = node.name
    if name not in spec.structs:
        fail("struct %s is not in the struct table of %s" % (name, os.path.basename(spec.path)))
    type_name, direction, table = spec.structs[name]
    struct = Struct(name, type_name, direction, docs.get(("struct", name), ""))
    offset = 0
    for decl in node.type.type.decls:
        declarator = decl.type
        if type(declarator).__name__ == "ArrayDecl":
            base, pointers, _ = type_of(declarator.type)
            length = int(declarator.dim.value)
            if base != "char":
                fail("%s.%s: only char arrays are expected" % (name, decl.name))
        else:
            base, pointers, _ = type_of(declarator)
            length = 0
            if base not in SCALARS or pointers:
                fail("%s.%s: unsupported field type %s" % (name, decl.name, base))
        if decl.name not in table:
            fail("field %s.%s is not in the struct table" % (name, decl.name))
        binding = table[decl.name]
        doc = docs.get(("field", name, decl.name), "")
        item = Field(decl.name, base, length, binding, doc)
        alignment = 1 if base == "char" else item.size
        if offset % alignment:
            fail("%s.%s would need compiler padding" % (name, decl.name))
        item.offset = offset
        offset += item.size
        check_field_binding(name, item, enums)
        struct.fields.append(item)
    struct.size = offset
    extra = sorted(set(table) - {item.name for item in struct.fields})
    if extra:
        fail("the struct table names fields of %s the header lacks: %s" % (name, " ".join(extra)))
    if [item.name for item in struct.fields] != list(table):
        fail("the struct table lists the fields of %s out of header order" % name)
    first = struct.fields[0]
    if (first.name, first.ctype, first.binding) != ("struct_size", "uint32_t", SIZE):
        fail("%s does not start with uint32_t struct_size" % name)
    return struct


def check_field_binding(struct_name, item, enums):
    where = "%s.%s" % (struct_name, item.name)
    binding = item.binding
    if binding in enums:
        if item.ctype not in ("uint32_t", "int32_t"):
            fail("%s: an enum field must be uint32_t or int32_t" % where)
    elif binding in (PATH, TEXT):
        if item.ctype != "char":
            fail("%s: a text field must be a char array" % where)
    elif binding in (INT, SIZE, RESERVED):
        if item.ctype == "char":
            fail("%s: a char array needs a text binding" % where)
    else:
        fail("%s: unknown binding type %s" % (where, binding))
    # A ::keel_<enum> reference states the field's type, unless it is a "see" cross-reference.
    for match in re.finditer(r"(?<![\w:])::(keel_[a-z_0-9]+)", item.doc):
        if match.group(1) in enums and not item.doc[:match.start()].rstrip().endswith("see"):
            if binding != match.group(1):
                fail("%s: the table says %s, its doc comment says %s" % (where, binding, match.group(1)))


def parse_function(node, docs, spec=KEEL_SPEC):
    name = node.name
    if name not in spec.functions:
        fail("function %s is not in the function table of %s" % (name, os.path.basename(spec.path)))
    result_type = type_of(node.type.type)
    params = []
    for param in node.type.args.params if node.type.args else []:
        if type(param).__name__ == "Typename":
            continue
        base, pointers, const = type_of(param.type)
        params.append(Param(param.name, base, pointers, const))
    result = Param("", *result_type)
    return Function(name, result, params, brief(docs.get(("function", name), "")))


def check_layout(model):
    layout = os.path.basename(model.spec.layout)
    pins = layout_pins(model.spec.layout)
    for name, struct in model.structs.items():
        if name not in pins:
            fail("%s pins no layout for %s" % (layout, name))
        offsets, size = pins[name]
        if [(item.name, item.offset) for item in struct.fields] != offsets or struct.size != size:
            fail("%s: the parsed layout differs from the %s pins" % (name, layout))
        if size > enum_value(model, "KEEL_STRUCT_SIZE_MAX"):
            fail("%s is larger than KEEL_STRUCT_SIZE_MAX" % name)


def check_packages(model):
    """The package table names a package for every enum and struct type of the header, and no other type."""
    table = model.spec.packages
    label = "PACKAGES" if table is PACKAGES else "CAMERA_PACKAGES"
    types = {enum.type_name for enum in model.enums.values()} | {struct.type_name for struct in model.structs.values()}
    missing = sorted(types - set(table))
    if missing:
        fail("the %s table has no package for: %s" % (label, " ".join(missing)))
    extra = sorted(set(table) - types)
    if extra:
        fail("the %s table names types %s lacks: %s" % (label, os.path.basename(model.spec.path), " ".join(extra)))
    clashes = sorted(set(PACKAGES) & set(CAMERA_PACKAGES))
    if clashes:
        fail("keel.h and camera.h types share the names: " + " ".join(clashes))


def enum_value(model, name):
    for enum in list(model.enums.values()) + list(model.foreign.values()):
        for enumerator in enum.enumerators:
            if enumerator.name == name:
                return enumerator.value
    fail("%s has no enumerator %s" % (os.path.basename(model.spec.path), name))



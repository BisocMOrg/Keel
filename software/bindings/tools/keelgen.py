def encode_path(struct: str, name: str, value: str | bytes, size: int) -> bytes:
    """Encode a path for a fixed char array of size bytes; raise ValueError if it does not fit."""
    if not isinstance(value, (str, bytes)):
        raise TypeError(f"{struct}: {name} must be str or bytes, not {type(value).__name__}; no call was made")
    encoded = os.fsencode(value)
    if b"\\0" in encoded or len(encoded) >= size:
        raise ValueError(f"{struct}: {name} must encode to at most {size - 1} bytes without NUL; no call was made")
    return encoded



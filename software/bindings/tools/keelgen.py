def py_boilerplate(model):
    return ("Everything here restates %s, so keelgen generates it and CI fails when the checked-in copy differs "
            "from a fresh run." % os.path.basename(model.spec.path))


def py_root(model):
    """The package the generated packages of a header re-export from: keel, or keel.camera."""
    return py_package("" if model.spec.name == "keel" else model.spec.name)


def python_package(model, package):
    """The public generated module of one package: the enums and data classes the package table assigns to it."""
    table = model.spec.packages
    enums = [enum for enum in model.enums.values() if enum.kind != "constants" and table[enum.type_name] == package]
    structs = [struct for struct in model.structs.values()
               if struct.direction == "out" and table[struct.type_name] == package]
    own = {item.type_name for item in enums + structs}
    label = py_package(package)
    if not own:
        fail("the package table gives %s no enum and no output struct" % label)
    keel_names = {}
    if any(enum.kind == "value" for enum in enums):
        keel_names[PY_VALUE_ENUM] = ["ValueEnum"]
    for struct in structs:
        for name in py_struct_types(model, struct) - own:
            keel_names.setdefault(py_module(name), []).append(name)
    standard = []
    if any(enum.kind == "flags" for enum in enums):
        standard.append("import enum")
    if structs:
        standard.append("from dataclasses import dataclass")
    contents = "enums and data classes" if structs else "enums"
    summary = "Header-derived %s of %s (%s %d.%d)." % ((contents, label, model.spec.library) + model.version[:2])
    root = py_root(model)
    exported = "%s re-exports" % root if label == root else "%s and %s re-export" % (label, root)
    body = "%s %s every name in __all__." % (py_boilerplate(model), exported)
    lines = py_header(summary, body, model.spec.notice) + py_imports(standard, keel_names)
    lines += ["", "__all__ = ["] + ['    "%s",' % name for name in sorted(own)] + ["]"]
    lines += py_enums(enums)
    for struct in structs:
        lines += py_dataclass(model, struct)
    return "\n".join(lines) + "\n"


def python_internal(model):
    """keel/_internal/_generated.py or keel/_internal/camera/_generated.py: the structs, conversions, prototypes,
    builders and checked calls of one header."""
    values = dict(major=model.version[0], minor=model.version[1], patch=model.version[2],
                  struct_size_max=enum_value(model, "KEEL_STRUCT_SIZE_MAX"), **PY_INTERNAL_VALUES[model.spec.name])
    converted = [struct for struct in model.structs.values() if struct.direction == "out"]
    keel_names = {}
    for struct in converted:
        for name in py_struct_types(model, struct) | {struct.type_name}:
            keel_names.setdefault(py_module(name), []).append(name)
    standard = ["import ctypes", "import operator", "import os", "from collections.abc import Callable",
                "from typing import Any, Final, SupportsIndex, TypeAlias"]
    if any(item.name == "bytes" and other.ctype == "char" for struct in model.structs.values()
           for item in struct.fields for other in struct.fields):
        standard.insert(0, "import builtins")
    summary = ("Header-derived private layer of %s %d.%d: structs, conversions, prototypes and checked calls."
               % ((model.spec.library,) + model.version[:2]))
    body = ("%s The public enums and data classes are in the _generated module of their package; everything here is "
            "private to the binding." % py_boilerplate(model))
    lines = py_header(summary, body, model.spec.notice) + py_imports(standard, keel_names) + [""]
    lines += (PY_INTERNAL_PREAMBLE % values).strip("\n").split("\n")
    lines += py_structs(model)
    for struct in converted:
        lines += py_converter(model, struct)
    lines += py_prototypes(model)
    lines += py_builders(model)
    lines += py_wrappers(model)
    return "\n".join(lines) + "\n"


def python_constants(model, enum_name, summary, body):
    enum = model.enums[enum_name]
    lines = py_header(summary, body, model.spec.notice) + ["from typing import Final", ""]
    names = []
    for enumerator in enum.enumerators:
        names.append(enumerator.member)
        lines += ["%s: Final = %d" % (enumerator.member, enumerator.value)]
        lines += py_attr_doc(clean(enumerator.doc), "")
    lines += ["", "__all__ = ["] + ['    "%s",' % name for name in sorted(names)] + ["]"]
    return "\n".join(lines) + "\n"


def python_version_check(model):
    """The hand-written files that restate a header agree with it.

    For keel.h: __version__ in keel/__init__.py, debian/changelog and the libkeel floor of debian/control follow the
    header's version, and the pseudo-member prefix of keel/_internal/value_enum.py is the sentinel keelgen checks the
    enumerators against. For camera.h: the libkeel-camera floor that debian/control recommends.
    """
    if model.spec.name == "camera":
        return python_camera_version_check(model)
    version = "%d.%d.%d" % model.version
    problems = []
    with open(os.path.join(PY_SOURCE, "__init__.py"), encoding="utf-8") as handle:
        match = re.search(r'^__version__ = "([^"]+)"$', handle.read(), re.M)
    if not match or match.group(1) != version:
        problems.append("keel/__init__.py __version__ is %s; keel.h says %s"
                        % (match.group(1) if match else "missing", version))
    with open(os.path.join(PYTHON, "debian", "changelog"), encoding="utf-8") as handle:
        match = re.search(r"^python-keel \(([^)]+)\)", handle.read(), re.M)
    if not match or match.group(1) != version:
        problems.append("python/debian/changelog is at %s; keel.h says %s"
                        % (match.group(1) if match else "missing", version))
    # python3-keel needs a library with the same major and at least its minor, never a patch level.
    floor = "%d.%d.0" % model.version[:2]
    with open(os.path.join(PYTHON, "debian", "control"), encoding="utf-8") as handle:
        match = re.search(r"libkeel%d \(>= ([^)]+)\)" % model.version[0], handle.read())
    if not match or match.group(1) != floor:
        problems.append("python/debian/control depends on libkeel%d (>= %s); keel.h needs (>= %s)"
                        % (model.version[0], match.group(1) if match else "missing", floor))
    with open(os.path.join(PY_SOURCE, "_internal", "value_enum.py"), encoding="utf-8") as handle:
        match = re.search(r'^SENTINEL: Final = "([^"]+)"$', handle.read(), re.M)
    if not match or match.group(1) != SENTINEL:
        problems.append("keel/_internal/value_enum.py names pseudo-members %s_<value>; keelgen checks %s"
                        % (match.group(1) if match else "(no SENTINEL)", SENTINEL))
    return problems


def python_camera_version_check(model):
    """python3-keel recommends the libkeel-camera package of camera.h's major, at least its minor."""
    floor = "%d.%d.0" % model.version[:2]
    with open(os.path.join(PYTHON, "debian", "control"), encoding="utf-8") as handle:
        match = re.search(r"^Recommends:.*libkeel-camera%d \(>= ([^)]+)\)" % model.version[0], handle.read(), re.M)
    if not match or match.group(1) != floor:
        return ["python/debian/control recommends libkeel-camera%d (>= %s); camera.h needs (>= %s)"
                % (model.version[0], match.group(1) if match else "missing", floor)]
    return []


